"""Score saved predictions against gold citations; no retrieval or model calls."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path

if __package__:
    from .challenge_tools.score_local import score as official_score, _paragraph_key
    from .challenge_tools.validate import read_submission, validate, load_index
else:
    from challenge_tools.score_local import score as official_score, _paragraph_key
    from challenge_tools.validate import read_submission, validate, load_index

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def file_sha256(path: Path) -> str:
    """Checksum of a text file with line endings normalised, so Windows (CRLF) and macOS/Linux (LF) checkouts of the
    same file agree and their runs land in the same leaderboard table."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


SCORER_SHA256 = file_sha256(HERE / "challenge_tools/score_local.py")
EVALUATOR = f"official-local-f2-v1-{SCORER_SHA256[:12]}"


def load_solution(path: Path, index: list | None = None) -> dict:
    doc = read_submission(path)
    problems = validate(doc, kind="main", index=index)
    if problems:
        raise ValueError(f"{path}: validation failed\n" + "\n".join(str(p) for p in problems))
    return doc


def clause_level(prediction: dict, gold: dict) -> dict:
    """Clause (paragraph) level, added by this evaluator: distinct (regulation, version, paragraph) cited vs gold, with
    the official paragraph normalisation. Stricter than the page level: a neighbouring paragraph on the right page does
    not count, and a requirement without a paragraph cites no clause."""
    def cited(doc: dict) -> set:
        return {(r["source"]["regulation"], r["source"].get("version", ""), key) for r in doc.get("requirements", [])
                if (key := _paragraph_key(r["source"].get("paragraph")))}
    submitted, expected = cited(prediction), cited(gold)
    matched = len(submitted & expected)
    precision = matched / len(submitted) if submitted else 0.0
    recall = matched / len(expected) if expected else 0.0
    return {"precision": precision, "recall": recall,
            "f1": 2 * precision * recall / (precision + recall) if precision + recall else 0.0,
            "n_submitted": len(submitted), "n_expected": len(expected), "n_matched": matched}


def score(prediction: dict, gold: dict) -> dict:
    """Use the unmodified challenge scorer, add the clause level, and add F2 to each metric group."""
    result = official_score(prediction, gold)
    result["clause_level"] = clause_level(prediction, gold)
    for level in result.values():
        precision, recall = level["precision"], level["recall"]
        denominator = 4 * precision + recall
        level["f2"] = 5 * precision * recall / denominator if denominator else 0.0
    return result


def fingerprint(doc: dict) -> str:
    canonical = json.dumps(doc, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def write_json(path: Path, value) -> None:
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def render_leaderboard(rows: list[dict]) -> str:
    latest = {}
    for row in rows:
        latest[(row["approach"], row["gold_sha256"], row["evaluator"])] = row
    rows = list(latest.values())
    lines = ["# Approach leaderboard", "",
             "Generated by `benchmarking/bench.py`. Ranked by page F2; regulation F2 breaks ties.",
             "Scores measure citation coverage, not requirement-text correctness.", ""]
    groups = sorted({(r["gold_sha256"], r["evaluator"]) for r in rows})
    for gold_hash, evaluator in groups:
        lines += [f"## Gold `{gold_hash[:12]}` · {evaluator}", "",
                  "| Rank | Approach | Page precision | Page recall | Page F2 | Clause F2 | Regulation F2 | Results |",
                  "| --- | --- | --- | --- | --- | --- | --- | --- |"]
        group = [r for r in rows if (r["gold_sha256"], r["evaluator"]) == (gold_hash, evaluator)]
        group.sort(key=lambda r: (-r["metrics"]["page_level"]["f2"],
                                  -r["metrics"]["regulation_level"]["f2"], r["approach"]))
        previous, rank = None, 0
        for position, row in enumerate(group, 1):
            page, reg = row["metrics"]["page_level"], row["metrics"]["regulation_level"]
            key = (page["f2"], reg["f2"])
            if key != previous:
                rank = position
            previous = key
            name = row["approach"]
            result_path = f"experiments/{name}/benchmark-results/{row['run_id']}.json"
            clause = row["metrics"].get("clause_level")  # absent on runs from before the clause level existed
            clause_f2 = f"{clause['f2']:.4f}" if clause else "—"
            lines.append(f"| {rank} | [{name}](experiments/{name}/) | {page['precision']:.4f} | "
                         f"{page['recall']:.4f} | {page['f2']:.4f} | {clause_f2} | {reg['f2']:.4f} | "
                         f"[JSON]({result_path}) |")
        lines.append("")
    if not rows:
        lines += ["No experiments have been scored yet.", ""]
    return "\n".join(lines)


def benchmark(name: str, prediction_path: Path, gold_path: Path, root: Path = ROOT, index_path: Path | None = None) -> dict:
    # The name identifies a folder under approaches/experiments/.
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]*", name):
        raise ValueError("name must contain only lowercase letters, digits, hyphens, or underscores")
    index = load_index(index_path) if index_path else None
    prediction, gold = load_solution(prediction_path, index), load_solution(gold_path, index)
    if prediction["case_id"] != gold["case_id"]:
        raise ValueError("prediction and gold case_id must match")
    if not gold["requirements"]:
        raise ValueError("gold solution must contain at least one requirement")
    experiments = root / "experiments"
    experiment = experiments / name
    if not experiment.resolve().is_relative_to(experiments.resolve()):
        raise ValueError("experiment directory must stay inside approaches/experiments")
    board_path = root / "leaderboard.json"
    rows = json.loads(board_path.read_text(encoding="utf-8")) if board_path.exists() else []
    gold_hash = fingerprint(gold)
    result = {
        "run_id": uuid.uuid4().hex,
        "approach": name,
        "status": "completed",
        "completed_at": datetime.now(timezone.utc).isoformat(),
        "evaluator": EVALUATOR,
        "scorer_sha256": SCORER_SHA256,
        "validation": {
            "prediction": "passed",
            "gold": "passed",
            "validator_sha256": file_sha256(HERE / "challenge_tools/validate.py"),
            "schema_sha256": file_sha256(HERE / "challenge_tools/schemas/submission_main.schema.json"),
            "index_path": str(index_path.resolve()) if index_path else None,
            "index_sha256": fingerprint(index) if index is not None else None,
            "regulation_versions_checked": index is not None,
        },
        "prediction_path": str(prediction_path.resolve()),
        "prediction_sha256": fingerprint(prediction),
        "gold_path": str(gold_path.resolve()),
        "gold_sha256": gold_hash,
        "ranking_metric": "page_level.f2",
        "metrics": score(prediction, gold),
    }
    rows.append(result)
    markdown = render_leaderboard(rows)
    archive = experiment / "benchmark-results"
    destinations = [experiment / "results.json", archive / f"{result['run_id']}.json",
                    board_path, root / "LEADERBOARD.md"]
    for destination in destinations:
        if not destination.resolve().is_relative_to(root.resolve()):
            raise ValueError("output paths must stay inside approaches")
        if destination.resolve() in {prediction_path.resolve(), gold_path.resolve()}:
            raise ValueError("input files must not be benchmark output files")
    archive.mkdir(parents=True, exist_ok=True)
    write_json(destinations[0], result)
    write_json(destinations[1], result)
    write_json(board_path, rows)
    destinations[3].write_text(markdown, encoding="utf-8")
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("name", help="experiment folder name, e.g. 001-bm25")
    parser.add_argument("prediction", type=Path, help="approach output JSON")
    parser.add_argument("gold", type=Path, help="sample solution JSON")
    parser.add_argument("--index", type=Path, help="optional regulations/index.json for regulation/version validation")
    args = parser.parse_args(argv)
    try:
        if args.index is None:
            print("note: regulation/version membership not checked; pass --index to enable", file=sys.stderr)
        result = benchmark(args.name, args.prediction, args.gold, index_path=args.index)
    except (OSError, ValueError, KeyError, TypeError, ImportError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
